def main():
    for batch_no, edits in EDITS.items():
        batch_id = f"batch_{batch_no:04d}"
        source_rel = f"work/translation/tm_v2/batches/source/{batch_id}.jsonl"
        draft_rel = f"work/translation/drafts/{batch_id}.jsonl"
        reviewed_rel = f"work/translation/reviewed/{batch_id}.jsonl"
        review_rel = f"work/translation/reviews/{batch_id}_review.json"

        draft_path = ROOT / draft_rel
        rows = [json.loads(line) for line in draft_path.read_text(encoding="utf-8").splitlines()]
        modifications = []
        for index, (after, category, reason) in edits.items():
            row = rows[index]
            before = row["translation_ko"]
            row["translation_ko"] = after
            modifications.append({
                "tm_id": row["tm_id"],
                "source_text": row["source_text"],
                "before": before,
                "after": after,
                "category": category,
                "reason": reason,
            })

        reviewed_path = ROOT / reviewed_rel
        reviewed_path.parent.mkdir(parents=True, exist_ok=True)
        reviewed_path.write_text(
            "".join(json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n" for row in rows),
            encoding="utf-8",
        )

        report = {
            "schema": "arf-translation-independent-review-v1",
            "batch_id": batch_id,
            "reviewer": REVIEWER,
            "draft_translator": DRAFT_AUTHOR,
            "draft_author": DRAFT_AUTHOR,
            "independent_review": True,
            "translation_engine_policy": "Codex internal models only",
            "external_translation_services_used": [],
            "external_translation_models_or_apis_used": [],
            "source": source_rel,
            "draft": draft_rel,
            "reviewed_output": reviewed_rel,
            "reviewed_units": len(rows),
            "modified_units": len(modifications),
            "unchanged_units": len(rows) - len(modifications),
            "review_dimensions": [
                "meaning", "function", "numeric fidelity", "proper nouns", "natural Korean",
                "particles", "control tokens", "line breaks",
            ],
            "modifications": modifications,
            "verification_execution": {
                "status": "deferred_by_user_instruction",
                "executed_tools": [],
                "not_executed": ["validator", "fit", "encoding", "boundary_audit"],
                "note": "사용자 지시에 따라 별도 validator, fit, encoding, boundary audit를 실행하지 않았다.",
            },
        }
        review_path = ROOT / review_rel
        review_path.parent.mkdir(parents=True, exist_ok=True)
        review_path.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"{batch_id}: reviewed={len(rows)} modified={len(modifications)}")


if __name__ == "__main__":
    main()
