if (rows.length !== 200 || Object.keys(translations).length !== 200) throw new Error("batch_0033 table incomplete");
for (let index = 1; index <= rows.length; index += 1) rows[index - 1].translation_ko = translations[index];
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, `${rows.map((row) => JSON.stringify(row)).join("\n")}\n`, "utf8");
process.stdout.write(`${JSON.stringify({ batch: "batch_0033", completed: rows.length })}\n`);
