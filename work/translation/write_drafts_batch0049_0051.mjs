function readJsonl(filePath) {
  return fs.readFileSync(filePath, "utf8").split(/\r?\n/).filter(Boolean).map(JSON.parse);
}

function writeBatch(batchId, translations) {
  const sourcePath = path.join(SOURCE_ROOT, `${batchId}.jsonl`);
  const outputPath = path.join(DRAFT_ROOT, `${batchId}.jsonl`);
  const rows = readJsonl(sourcePath);
  for (let index = 0; index < rows.length; index += 1) {
    rows[index].translation_ko = translations[index];
  }
  fs.mkdirSync(DRAFT_ROOT, { recursive: true });
  fs.writeFileSync(outputPath, `${rows.map((row) => JSON.stringify(row)).join("\n")}\n`, "utf8");
  process.stdout.write(`${batchId}: ${rows.length}\n`);
}

for (const [batchId, translations] of Object.entries(TRANSLATIONS)) {
  writeBatch(batchId, translations);
}
